export function cacheSchemesOffline(): void {
  if (typeof localStorage === "undefined") return;
  localStorage.setItem("sahay_schemes_cache", JSON.stringify(SCHEMES));
  localStorage.setItem("sahay_schemes_cached_at", new Date().toISOString());
}

export function loadCachedSchemes(): SchemeRecord[] | null {
  if (typeof localStorage === "undefined") return null;
  const raw = localStorage.getItem("sahay_schemes_cache");
  if (!raw) return null;
  try {
    return JSON.parse(raw) as SchemeRecord[];
  } catch {
    return null;
  }
}
