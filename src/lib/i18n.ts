/** Map localized answers back to English keys for the engine */
export function normalizeEligibilityAnswers(
  answers: string[],
  lang: LangCode,
): import("./types").EligibilityAnswers {
  const en = eligibilityQuestions.en;
  const localized = eligibilityQuestions[lang] ?? en;

  const pick = (i: number) => {
    const val = answers[i] ?? "";
    const enIdx = localized[i]?.a.indexOf(val);
    if (enIdx !== undefined && enIdx >= 0) return en[i].a[enIdx];
    return val;
  };

  return {
    land: pick(0),
    income: pick(1),
    state: pick(2),
    primaryEarner: pick(3),
    aadhaarBank: pick(4),
  };
}
